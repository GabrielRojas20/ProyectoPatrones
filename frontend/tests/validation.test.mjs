import assert from 'node:assert/strict';
import { alphanumeric, digits, emailChars, letters, MAX, productSearchText, today, validCedula, validEmail, validPersonName, saleStatusLabel } from '../shared/validation.js';

assert.equal(letters('Ana123 Pérez!').length, 'Ana Pérez'.length);
assert.equal(digits('17-123abc4567').slice(0, 10), '171234567');
assert.equal(alphanumeric('A-12_x').includes('-'), false);
assert.equal(emailChars('ana+test@gmail.com'), 'ana+test@gmail.com');
assert.equal(letters('x'.repeat(80)).length, MAX);
assert.equal(MAX, 35);
assert.equal(validPersonName('  Ana   Pérez  '), true);
assert.equal(validPersonName('Ana123 Pérez'), false);
assert.equal(validPersonName('A'.repeat(35)), true);
assert.equal(validPersonName('A'.repeat(36)), false);
assert.equal(validPersonName('Ana María Lara'), true);
assert.equal(validPersonName('Ana-Lara'), false);
assert.equal(productSearchText('Laptop X15 Pro+'), 'Laptop X15 Pro+');
assert.equal(validCedula('1712345678'), true);
assert.equal(validCedula('171234567'), false);
assert.equal(validEmail('persona@gmail.com'), true);
assert.equal(validEmail('persona+pos@correo.com'), true);
assert.equal(validEmail('ana.apellido_1@sub.d.co.uk'), true);
assert.equal(validEmail(`a${'b'.repeat(31)}@x.co`), false);
assert.equal(validEmail('persona@sub.correo.co.uk'), true);
assert.equal(validEmail('persona@gmail..com'), false);
assert.equal(validEmail(`persona${'x'.repeat(30)}@a.com`), false);
assert.equal(saleStatusLabel('paid'), 'Pagada');
assert.equal(saleStatusLabel('unexpected'), 'Estado no disponible');
assert.equal(today().length, 10);
console.log('Frontend validation checks: 26 assertions passed');
